/* =====================
   星座判定
===================== */
function zodiac(month, day) {
  const list = [
    [120, "みずがめ座"],
    [219, "うお座"],
    [321, "おひつじ座"],
    [420, "おうし座"],
    [521, "ふたご座"],
    [621, "かに座"],
    [722, "しし座"],
    [822, "おとめ座"],
    [922, "てんびん座"],
    [1023, "さそり座"],
    [1122, "いて座"],
    [1222, "やぎ座"],
  ];
  const md = month * 100 + day;
  for (let i = list.length - 1; i >= 0; i--) {
    if (md >= list[i][0]) return list[i][1];
  }
  return "やぎ座";
}

