// 星座判定
function zodiac(m, d) {
  const z = [
    [120, "みずがめ座"],
    [219, "うお座"],
    [321, "おひつじ座"],
    [420, "おうし座"],
    [521, "ふたご座"],
    [621, "かに座"],
    [722, "しし座"],
    [822, "おとめ座"],
    [922, "てんびん座"],
    [1023, "さそり座"],
    [1122, "いて座"],
    [1222, "やぎ座"],
  ];
  const md = m * 100 + d;
  for (let i = z.length - 1; i >= 0; i--) {
    if (md >= z[i][0]) return z[i][1];
  }
  return "やぎ座";
}

