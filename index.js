/* =====================
   コマンド処理
===================== */
client.on("interactionCreate", async (interaction) => {
  if (!interaction.isChatInputCommand()) return;
  if (interaction.commandName !== "uranai") return;

  // ★ 最重要：最初に必ず非公開宣言
  await interaction.deferReply({ ephemeral: true });

  const input = interaction.options.getString("birthday");
  const date = new Date(input);

  // 入力ミス対策（ここも非公開）
  if (isNaN(date.getTime())) {
    await interaction.editReply(
      "❌ 誕生日の形式が正しくありません。\n例：`2010-03-26`"
    );
    return;
  }

  const day = date.getDate();
  const sign = zodiac(date.getMonth() + 1, day);
  const animal = eto[(date.getFullYear() - 4) % 12];

  await interaction.editReply({
    content: `🎂 **占い結果**

💰 **金運**：${money[day][0]}位（${money[day][1]}）
🩺 **健康運**：${health[sign][0]}位（${health[sign][1]}）
❤️ **出会い運**：${meet[animal][0]}位（幸運人：${meet[animal][1]}）`,
  });
});

